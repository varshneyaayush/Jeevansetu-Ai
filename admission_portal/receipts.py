"""
admission_portal/receipts.py
-----------------------------
PDF receipt generator using fpdf2.
Falls back to a pure-Python minimal PDF if fpdf2 is not installed.
"""
from __future__ import annotations

from datetime import datetime, timezone


def generate_receipt_pdf(
    request_id: int,
    patient_name: str,
    hospital_id: str,
    amount_paise: int,
    razorpay_payment_id: str,
    paid_at: str,
) -> bytes:
    """
    Generate a PDF payment receipt. Returns PDF bytes.
    Uses fpdf2 if available, otherwise falls back to pure-Python PDF.
    """
    amount_rupees = amount_paise / 100.0
    receipt_no = f"RCP-{request_id}-{int(datetime.now(timezone.utc).timestamp())}"

    try:
        return _generate_fpdf2_receipt(
            receipt_no=receipt_no,
            request_id=request_id,
            patient_name=patient_name,
            hospital_id=hospital_id,
            amount_rupees=amount_rupees,
            razorpay_payment_id=razorpay_payment_id,
            paid_at=paid_at,
        )
    except ImportError:
        return _generate_fallback_receipt(
            receipt_no=receipt_no,
            request_id=request_id,
            patient_name=patient_name,
            hospital_id=hospital_id,
            amount_rupees=amount_rupees,
            razorpay_payment_id=razorpay_payment_id,
            paid_at=paid_at,
        )


def _generate_fpdf2_receipt(
    receipt_no: str,
    request_id: int,
    patient_name: str,
    hospital_id: str,
    amount_rupees: float,
    razorpay_payment_id: str,
    paid_at: str,
) -> bytes:
    from fpdf import FPDF

    pdf = FPDF(orientation="P", unit="mm", format="A4")
    pdf.add_page()
    pdf.set_margins(20, 20, 20)
    pdf.set_auto_page_break(auto=True, margin=20)

    # ---- Header ----
    pdf.set_fill_color(31, 61, 43)   # Forest green
    pdf.rect(0, 0, 210, 38, style="F")
    pdf.set_text_color(245, 239, 230)  # Cream
    pdf.set_font("Helvetica", "B", 20)
    pdf.set_xy(20, 10)
    pdf.cell(0, 10, "JeevanSetu AI", ln=False)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_xy(20, 22)
    pdf.cell(0, 6, "Emergency Pre-Admission Portal — Payment Receipt", ln=True)

    # ---- Receipt Title ----
    pdf.set_text_color(31, 61, 43)
    pdf.set_xy(20, 48)
    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 10, "ADMISSION DEPOSIT RECEIPT", ln=True, align="C")

    # ---- Divider ----
    pdf.set_draw_color(31, 61, 43)
    pdf.set_line_width(0.5)
    pdf.line(20, 62, 190, 62)

    # ---- Receipt Info Grid ----
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(90, 107, 97)

    def row(label: str, value: str, y: float) -> None:
        pdf.set_xy(20, y)
        pdf.set_text_color(90, 107, 97)
        pdf.cell(55, 7, label + ":", ln=False)
        pdf.set_text_color(27, 43, 33)
        pdf.set_font("Helvetica", "B", 10)
        pdf.cell(0, 7, value, ln=True)
        pdf.set_font("Helvetica", "", 10)

    y = 68
    row("Receipt No.", receipt_no, y); y += 10
    row("Admission Request", f"#{request_id}", y); y += 10
    row("Patient Name", patient_name or "—", y); y += 10
    row("Hospital ID", hospital_id or "—", y); y += 10
    row("Payment ID (Razorpay)", razorpay_payment_id or "—", y); y += 10
    row("Payment Date & Time", paid_at or "—", y); y += 10

    # ---- Amount Box ----
    pdf.set_fill_color(236, 246, 239)  # Light green
    pdf.set_draw_color(47, 122, 85)
    pdf.set_line_width(0.8)
    pdf.rect(20, y + 4, 170, 24, style="FD")
    pdf.set_xy(20, y + 7)
    pdf.set_font("Helvetica", "", 11)
    pdf.set_text_color(31, 61, 43)
    pdf.cell(85, 10, "Amount Paid:", ln=False)
    pdf.set_font("Helvetica", "B", 16)
    pdf.set_text_color(31, 61, 43)
    pdf.cell(0, 10, f"INR {amount_rupees:,.2f}", ln=True)

    y += 36
    # ---- Disclaimer ----
    pdf.set_xy(20, y)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(90, 107, 97)
    pdf.multi_cell(
        170, 5,
        "IMPORTANT: Emergency medical treatment does NOT depend on payment. "
        "This receipt is for admission deposit / formalities only. "
        "Treatment has already begun / will begin regardless of payment status.",
    )

    # ---- Footer ----
    pdf.set_text_color(90, 107, 97)
    pdf.set_font("Helvetica", "", 8)
    pdf.set_xy(20, 270)
    pdf.cell(0, 5, "Generated by JeevanSetu AI Emergency Pre-Admission Portal | Team Optimove", align="C")

    return bytes(pdf.output())


def _generate_fallback_receipt(
    receipt_no: str,
    request_id: int,
    patient_name: str,
    hospital_id: str,
    amount_rupees: float,
    razorpay_payment_id: str,
    paid_at: str,
) -> bytes:
    """Pure-Python minimal PDF (no external deps) — same approach as app.py."""
    lines = [
        "JEEVANSETU AI - EMERGENCY PRE-ADMISSION PORTAL",
        "PAYMENT RECEIPT",
        "============================================================",
        f"Receipt No.         : {receipt_no}",
        f"Admission Request   : #{request_id}",
        f"Patient Name        : {patient_name or '-'}",
        f"Hospital ID         : {hospital_id or '-'}",
        f"Payment ID          : {razorpay_payment_id or '-'}",
        f"Paid At             : {paid_at or '-'}",
        f"Amount Paid (INR)   : {amount_rupees:,.2f}",
        "============================================================",
        "DISCLAIMER: Emergency treatment does NOT wait for payment.",
        "This is for admission deposit/formalities only.",
        "------------------------------------------------------------",
        "Generated by JeevanSetu AI | Team Optimove",
    ]
    content = "BT\n/F1 12 Tf\n45 785 Td\n"
    y = 785
    for line in lines:
        clean = line.replace("(", "[").replace(")", "]").replace("\\", "/")
        content += f"({clean}) Tj\n0 -18 Td\n"
        y -= 18
        if y < 60:
            break
    content += "ET\n"
    stream_bytes = content.encode("latin1", errors="replace")
    slen = len(stream_bytes)
    objs = [
        b"%PDF-1.4\n",
        b"1 0 obj << /Type /Catalog /Pages 2 0 R >> endobj\n",
        b"2 0 obj << /Type /Pages /Kids [3 0 R] /Count 1 >> endobj\n",
        b"3 0 obj << /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >> endobj\n",
        f"4 0 obj << /Length {slen} >>\nstream\n".encode("latin1") + stream_bytes + b"\nendstream\nendobj\n",
        b"5 0 obj << /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >> endobj\n",
    ]
    xref_pos = sum(len(o) for o in objs)
    cur = len(objs[0])
    xref = "xref\n0 6\n0000000000 65535 f \n"
    for i in range(1, 5):
        xref += f"{cur:010d} 00000 n \n"
        cur += len(objs[i])
    xref += f"{cur:010d} 00000 n \n"
    trailer = f"trailer << /Size 6 /Root 1 0 R >>\nstartxref\n{xref_pos}\n%%EOF\n"
    return b"".join(objs) + xref.encode("latin1") + trailer.encode("latin1")
